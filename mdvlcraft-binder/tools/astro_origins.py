def glyph_image(art):
    rows = [r for r in art.strip('\n').split('\n')]
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows[:16]):
        for x, ch in enumerate(row[:16]):
            if ch == '#':
                im.putpixel((x, y), (235, 240, 255, 255))
            elif ch == '+':
                im.putpixel((x, y), (60, 70, 110, 255))
    return im


def icons():
    races = json.loads((OVERRIDES / 'origins/origin_layers/origin.json').read_text())['origins']
    classes = data('origins-classes', 'origin_layers', 'class')['origins']
    ICON_TEX.mkdir(parents=True, exist_ok=True)
    MODELS.mkdir(parents=True, exist_ok=True)
    numbering, overrides = {}, []
    for n, oid in enumerate(races + classes, start=1):
        ns, path = oid.split(':')
        name = f"{ns.replace('-', '_')}_{path}"
        if oid in RACE_GLYPHS:  # races: a simple silhouette, the same for every race mod
            src = glyph_image(RACE_GLYPHS[oid])
        else:  # classes: drawn from the class's own item
            src = original_icon(data(ns, 'origins', path, jar_only=True)['icon'])
        kind = 'archetype' if oid in races else 'skill'  # races in starlight blue, classes in gold
        astro.pixel_icon(src, kind, f'origin/{name}', 16).save(ICON_TEX / f'{name}.png')  # item size, one pixel per GUI pixel
        (MODELS / f'origin/{name}.json').parent.mkdir(parents=True, exist_ok=True)
        (MODELS / f'origin/{name}.json').write_text(json.dumps(
            {'parent': 'minecraft:item/generated', 'textures': {'layer0': f'mdvlcraft:item/origin/{name}'}}, indent=2) + '\n')
        overrides.append({'predicate': {'custom_model_data': n}, 'model': f'mdvlcraft:item/origin/{name}'})
        numbering[oid] = n
    (MODELS / 'origin_icon.json').write_text(json.dumps(
        {'parent': 'minecraft:item/generated', 'textures': {'layer0': f"mdvlcraft:item/origin/{next(iter(numbering)).replace(':', '_').replace('-', '_')}"},
         'overrides': overrides}, indent=2) + '\n')
    (PACK / 'origin_icons.json').write_text(json.dumps(numbering, indent=2) + '\n')
    return numbering


# ------------------------------------------------------------------------------------- screen textures
NAVY = [(5, 7, 15), (8, 10, 24), (12, 15, 36), (18, 23, 52), (26, 32, 70), (40, 48, 92)]
GOLD = {(170, 126, 15): (170, 140, 80), (219, 162, 19): (224, 194, 122), (73, 54, 6): (60, 48, 26),
        (255, 255, 255): (170, 140, 80)}
TILES = {(155, 219, 149): (76, 92, 150), (47, 99, 55): (26, 32, 70)}


def sky(x, y, h, faint=False):
    """The night sky inside a panel: a soft vertical gradient with a few fixed stars (fewer and dimmer behind text)."""
    t = y / max(1, h)
    base = tuple(int(a + (b - a) * t) for a, b in zip((14, 18, 44), (8, 11, 30)))
    roll = hashlib.md5(f'{x},{y}'.encode()).digest()[0]
    if roll > 253:
        return (60, 70, 112) if faint else (196, 208, 240)
    if roll > 250 and not faint:
        return (70, 82, 128)
    return base


def recolour(im, faint=False):
    im = im.convert('RGBA')
    px = im.load()
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = px[x, y]
            if a == 0:
                continue
            c = (r, g, b)
            if c == (85, 85, 85):
                c = sky(x, y, im.height, faint)
            elif c in GOLD:
                c = GOLD[c]
            elif c in TILES:
                c = TILES[c]
            elif r == g == b:  # the grey bevel ramp becomes navy
                c = NAVY[min(len(NAVY) - 1, r * len(NAVY) // 256)]
            px[x, y] = c + (a,)
    return im


def badge(src):
    """A power badge as a small astrolabe disc: navy face, rim in the badge's colour, its glyph in starlight."""
    src = src.convert('RGBA')
    w, h = src.size
    px = src.load()
    counts = {}
    for y in range(h):
        for x in range(w):
            c = px[x, y]
            if c[3] and c[:3] != (0, 0, 0):
                counts[c[:3]] = counts.get(c[:3], 0) + 1
    hue = max(counts, key=counts.get) if counts else (200, 212, 235)
    out = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(out)
    d.ellipse((0, 0, w - 1, h - 1), fill=NAVY[3] + (255,), outline=hue + (255,))
    op = out.load()
    for y in range(2, h - 2):
        for x in range(2, w - 2):  # the glyph: black pixels inside the badge's border
            if px[x, y][3] and px[x, y][:3] == (0, 0, 0):
                op[x, y] = tuple(min(255, int(v * 0.35 + 170)) for v in hue) + (255,)
    return out


UI_PACK = PACK / 'client-overrides/resourcepacks/MDVLCraft-Astrologer-UI.zip'
