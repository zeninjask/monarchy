#!/usr/bin/env python3
"""The Astrologer's look for the race and class pickers (Origins, Alternate Origin GUI, Origins: Classes).

Every race and class in the game gets its own star icon, drawn from its current icon, so the Medieval Origins,
Origins++ and Classes icons stop looking like three different mods. The icons are shown by one hidden Binder item
(mdvlcraft:origin_icon) that picks its texture by CustomModelData; modpack/origins_overrides.py points every
race and class at it (modpack/origin_icons.json holds the numbering). The picker panel, the origin list and the
power badges are recoloured into the night-sky palette, keeping their layout, in a resource pack the client
packs list above the mods' resources (modpack/client-overrides/resourcepacks/MDVLCraft-Astrologer-UI.zip).

Usage (from mdvlcraft-binder/, after modpack/origins_overrides.py has written the race list):
  python3 tools/astro_origins.py <vanilla 1.20.1 client jar>
"""
