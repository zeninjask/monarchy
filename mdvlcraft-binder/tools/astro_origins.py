PACK = BINDER.parent / 'modpack'
OVERRIDES = PACK / 'overrides/kubejs/data'
ORIGIN_JARS = ('origins-forge-', 'Medieval Origins Revival-', 'origins-plus-plus-', 'origins-classes-forge-')
ICON_TEX = RES / 'assets/mdvlcraft/textures/item/origin'
MODELS = RES / 'assets/mdvlcraft/models/item'
ICON_ITEM = 'mdvlcraft:origin_icon'


def jars():
    shipped = {Path(f['path']).name for f in json.load(open(PACK / 'client.modrinth.index.json'))['files']}
    return [zipfile.ZipFile(BINDER / 'libs/modpack' / n) for n in sorted(shipped)
            if n.startswith(ORIGIN_JARS) and (BINDER / 'libs/modpack' / n).exists()]


ZIPS = jars()


def data(ns, kind, path, jar_only=False):
    over = OVERRIDES / ns / kind / f'{path}.json'
    if over.exists() and not jar_only:
        return json.loads(over.read_text())
    for z in ZIPS:
        if f'data/{ns}/{kind}/{path}.json' in z.namelist():
            return json.loads(z.read(f'data/{ns}/{kind}/{path}.json'))
    raise SystemExit(f'{ns}:{kind}/{path} not found')


def asset_json(rl, kind):
    ns, path = rl.split(':', 1)
    name = f'assets/{ns}/{kind}/{path}.json'
    for z in ZIPS + [zipfile.ZipFile(j) for j in astro.JARS if j.endswith('.jar')]:
        if name in z.namelist():
            return json.loads(z.read(name))
    return None


def original_icon(icon):
    """The picture the race or class shows today (following Medieval Origins' CustomModelData models)."""
    if isinstance(icon, str):
        icon = {'item': icon}
    item = icon['item']
    if item == ICON_ITEM:
        raise SystemExit('icons were already swapped: re-run modpack/origins_overrides.py first')
    if item == 'minecraft:player_head':  # Human: the default player face
        return astro.load_texture('minecraft:textures/entity/player/wide/steve.png').crop((8, 8, 16, 16))
    cmd = None
    if 'CustomModelData:' in icon.get('tag', ''):
        cmd = int(icon['tag'].split('CustomModelData:')[1].split('}')[0])
    if cmd is not None:
        ns, path = item.split(':')
        model = asset_json(f'{ns}:item/{path}', 'models')
        for o in (model or {}).get('overrides', []):
            if o['predicate'].get('custom_model_data') == cmd:
                sub = asset_json(o['model'], 'models')
                return astro.load_texture(sub['textures']['layer0'].replace(':', ':textures/', 1) + '.png')
    animated = {'minecraft:compass': 'compass_16', 'minecraft:clock': 'clock_00'}  # items drawn from animation frames
    if item in animated:
        return astro.load_texture(f'minecraft:textures/item/{animated[item]}.png')
    return astro.source_image({'type': 'item', 'data': {'item': item}})


